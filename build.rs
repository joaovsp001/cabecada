// Build-time helpers.
//
// 1. The window library links imm32 (Windows text input). Some MinGW setups ship without
//    its import library, so on windows-gnu we let the linker read the system's imm32.dll
//    directly (GNU ld can link against a DLL).
//
// 2. Drop-in pictures and music: every PNG in `assets/ui/` and every `.ogg`/`.wav` in
//    `assets/music/` is embedded in the game automatically. The code looks them up by
//    file name (without the extension) and falls back to its own drawing when a file is
//    missing, so new art can be added just by putting the file in the folder.
use std::fmt::Write as _;
use std::path::Path;

fn main() {
    let target = std::env::var("TARGET").unwrap_or_default();
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap());
    if target.ends_with("windows-gnu") {
        let windir = std::env::var("SystemRoot").unwrap_or_else(|_| "C:\\Windows".into());
        let src = Path::new(&windir).join("System32").join("imm32.dll");
        if src.exists() && std::fs::copy(&src, out.join("imm32.dll")).is_ok() {
            println!("cargo:rustc-link-search=native={}", out.display());
        }
    }

    let root = std::path::PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let mut code = String::from("// Generated by build.rs: optional pictures and music found in assets/ui and assets/music.\n");
    code.push_str("pub static UI: &[(&str, &[u8])] = &[\n");
    for (name, path) in files_in(&root.join("assets").join("ui"), &["png"]) {
        writeln!(code, "    ({:?}, include_bytes!({:?})),", name, path).unwrap();
    }
    code.push_str("];\n");
    code.push_str("pub static MUSIC: &[(&str, &[u8])] = &[\n");
    for (name, path) in files_in(&root.join("assets").join("music"), &["ogg", "wav"]) {
        writeln!(code, "    ({:?}, include_bytes!({:?})),", name, path).unwrap();
    }
    code.push_str("];\n");
    std::fs::write(out.join("optional_assets.rs"), code).unwrap();

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=assets/ui");
    println!("cargo:rerun-if-changed=assets/music");
}

/// (file name without extension, absolute path) of the files with one of `exts`, sorted.
fn files_in(dir: &Path, exts: &[&str]) -> Vec<(String, String)> {
    let mut v = vec![];
    if let Ok(rd) = std::fs::read_dir(dir) {
        for e in rd.flatten() {
            let p = e.path();
            let ext = p.extension().and_then(|x| x.to_str()).unwrap_or("").to_ascii_lowercase();
            if p.is_file() && exts.contains(&ext.as_str()) {
                let name = p.file_stem().and_then(|x| x.to_str()).unwrap_or("").to_string();
                println!("cargo:rerun-if-changed={}", p.display());
                v.push((name, p.to_string_lossy().into_owned()));
            }
        }
    }
    v.sort();
    v
}
